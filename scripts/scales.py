#!/usr/bin/env python3
"""Type, spacing, radius and motion scales as CSS tokens.

  scales.py [--base 14] [--ratio 1.2] [--unit 4] [--density compact|normal|airy] [--target widget|app|web|mobile] [--css out.css]
Type steps from a modular ratio, rounded to 0.5 px; spacing from a unit on a 1-2-3-4-6-8-12-16 ladder;
radius tied to element size; motion durations and easings by distance travelled.
"""
import argparse
a = argparse.ArgumentParser()
a.add_argument("--base", type=float); a.add_argument("--ratio", type=float)
a.add_argument("--unit", type=int); a.add_argument("--density", default="normal", choices=["compact", "normal", "airy"])
a.add_argument("--target", default="app", choices=["widget", "app", "web", "mobile"]); a.add_argument("--css")
o = a.parse_args()
d = {"widget": (13, 1.15, 4), "app": (14, 1.2, 4), "web": (16, 1.25, 4), "mobile": (16, 1.2, 4)}[o.target]
base, ratio, unit = o.base or d[0], o.ratio or d[1], o.unit or d[2]
rnd = lambda x: round(x * 2) / 2
steps = {"2xs": -2, "xs": -1, "s": 0, "m": 1, "l": 2, "xl": 3, "2xl": 4}
fs = {k: rnd(base * ratio ** (n - 0)) if n > 0 else rnd(base * ratio ** n) for k, n in steps.items()}
fs["s"] = base
fs = {k: max(v, 11) for k, v in fs.items()}
lh = {k: (1.5 if fs[k] <= 16 else 1.3 if fs[k] <= 24 else 1.15) for k in fs}
sp_ladder = [1, 2, 3, 4, 6, 8, 12, 16]
mult = {"compact": .75, "normal": 1, "airy": 1.35}[o.density]
sp = [round(unit * n * mult / 2) * 2 for n in sp_ladder]
r_small, r_med, r_large = round(base * .3), round(base * .6), round(base * 1.0)
lines = ["/* generated by scales.py */", ":root{"]
for k, v in fs.items(): lines.append(f"  --fs-{k}: {v:g}px; --lh-{k}: {lh[k]};")
for i, v in enumerate(sp, 1): lines.append(f"  --sp-{i}: {v}px;")
lines += [f"  --radius-s: {r_small}px; --radius-m: {r_med}px; --radius-l: {r_large}px; --radius-pill: 999px;",
          "  --dur-micro: 120ms; --dur-small: 200ms; --dur-large: 300ms; --dur-xl: 450ms;",
          "  --ease-out: cubic-bezier(.2,.8,.2,1); --ease-in: cubic-bezier(.4,0,1,1); --ease-inout: cubic-bezier(.65,0,.35,1);",
          "  --stroke: 1.5px; --icon-s: 16px; --icon-m: 20px; --icon-l: 24px;", "}"]
out = "\n".join(lines); print(out)
if o.css: open(o.css, "w").write(out + "\n"); print("wrote", o.css)
